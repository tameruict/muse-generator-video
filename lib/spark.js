const fs = require('fs'), path = require('path');
const { langName } = require('./lang');
const { t } = require('./i18n');

// ---- Tách danh sách cảnh từ câu trả lời của Muse, thử nhiều cách ----
function stripFences(s) { return String(s || '').replace(/```[a-z]*\s*/gi, '').replace(/```/g, '').trim(); }
function clean(x) { return String(x).replace(/^\s*(shot|cảnh|scene)\s*\d+\s*[:.\-–)]\s*/i, '').trim(); }

function tryJson(t) {
  const fix = s => s
    .replace(/[\u201C\u201D\u201E]/g, '"').replace(/[\u2018\u2019]/g, "'")   // nháy cong -> thẳng
    .replace(/,\s*([\]}])/g, '$1');                                          // dấu phẩy thừa cuối mảng
  const a = t.indexOf('['), b = t.lastIndexOf(']');
  if (a < 0 || b <= a) return null;
  const cands = [t.slice(a, b + 1)]; cands.push(fix(cands[0]));
  for (const c of cands) {
    try {
      let arr = JSON.parse(c);
      if (arr && !Array.isArray(arr) && typeof arr === 'object') arr = arr.shots || arr.scenes || Object.values(arr);
      if (Array.isArray(arr)) return arr.map(x => typeof x === 'string' ? x : (x && (x.prompt || x.text || x.description)) || '').map(clean).filter(Boolean);
    } catch (_) {}
  }
  // lời thoại có dấu " chưa escape làm hỏng JSON: tách theo mẫu  "...",\n"..."
  const body = cands[1].replace(/^\[\s*"/, '').replace(/"\s*\]$/, '');
  const parts = body.split(/"\s*,\s*\n\s*"/).map(clean).filter(Boolean);
  return parts.length > 1 ? parts : null;
}
function tryDelimited(t) {            // ### SHOT 1 ... ### SHOT 2 ...  (định dạng chính, không cần escape)
  if (!/^\s*#{2,}\s*(?:shot|cảnh|scene)\s*\d+/im.test(t)) return null;
  const parts = t.split(/^\s*#{2,}\s*(?:shot|cảnh|scene)\s*\d+[^\n]*\n/im).map(s => s.trim()).filter(Boolean);
  return parts.length ? parts.map(clean) : null;
}
function tryNumbered(t) {             // "1. ...", "Shot 2: ...", "Cảnh 3 - ..."
  const parts = t.split(/^\s*(?:(?:shot|cảnh|scene)\s*)?\d+\s*[.:)\-–]\s+/im).map(s => s.trim()).filter(Boolean);
  return parts.length > 1 ? parts.map(clean) : null;
}
function parseShots(out) {
  const t = stripFences(out);
  for (const f of [tryDelimited, tryJson, tryNumbered]) { const r = f(t); if (r && r.length) return r; }
  return null;
}

function systemPrompt(n, voice, hasChars, film) {
  const ln = langName(voice);
  return 'You are a short-video director. Write EXACTLY ' + n + ' shots for ONE continuous story. ' +
    'Each shot is ONE ~10 second take, written as a self-contained English prompt in this order: subject + ONE clear action (at most two simple beats, never a montage), setting, ONE camera move, lighting, lens/film look. ' +
    'Every shot is generated by an AI video model that CANNOT see the other shots, so every prompt must restate what must stay identical: the location look and each visible character\'s fixed outfit and hair in a few words. ' +
    'FIDELITY (most important): the user\'s idea is the source of truth. Keep EVERY subject, object, place, action, emotion, product detail and spoken line the user wrote, in the same order; never replace, drop, soften or reinterpret them, and never add new plot events, characters or props the user did not mention. You may only add camera, lighting, lens and texture detail. If the idea has more content than fits one shot, split it across the shots in order instead of cutting it. ' +
    'Keep the same characters, outfits, location and visual style across shots; each shot continues directly from the previous one (same time of day, same weather, same props). ' +
    'CONTINUITY (the clips are joined into one long video, so each cut must be invisible): every shot except the first must START from the exact situation where the previous shot ENDED (same place, same people, same poses and positions, same camera side), then advance the story; open its prompt with a short clause such as "Continuing right after <previous end state>:". ' +
    'End every shot on a calm, clearly described final moment (a held pose, a look, a settled camera) instead of mid-action, a cut-away or a scene change, so the next shot can pick up from it. Inside one shot use no cuts, no montage, no time jumps; never repeat an action already shown in an earlier shot. ' +
    'EXCEPTION: when the story deliberately moves to a NEW place or a clearly later time, start that shot prompt with "NEW SEQUENCE:" (after the character tag if any) and establish the new place; use this at most once per ~6 shots and only where the story really changes location or time. ' +
    'Show at most 2 characters in one shot unless the story truly needs more; crowds are only background silhouettes. ' +
    (ln ? `Spoken lines (if any) are in ${ln}, short (max ~20 words per shot), written inside the shot as: says in ${ln}: "...". ` : 'No spoken dialogue. ') +
    (film ? 'This is a cinematic film: photorealistic, motivated camera, natural acting, consistent cinematography. ' : '') +
    'SAFETY (the video generator refuses otherwise): never use the name of any real person, historical or living, in a shot; describe them by role, age and clothing instead (e.g. \'a French general in a 1950s dress uniform\'). Never depict capture, arrest, violence, injuries or weapons aimed at anyone; convey conflict only by implication (tense silence, raised hands, a door opening, a flag lowered, reactions). ' +
    'Disasters, wars and end-of-world events (earthquakes, collapsing buildings, fires, floods, explosions, crashes, panicking crowds) are also refused when shown directly: convey scale and threat through the sky, light, reflections, swaying objects, drifting dust, distant skylines, small silhouettes looking up and reactions, and show aftermath or anticipation instead of the destruction itself. ' +
    'FORMAT (strict): output ' + n + ' blocks, each starting with a line "### SHOT k" (k = 1..' + n + ') followed by the prompt as plain text. ' +
    'No JSON, no markdown fences, no intro, no outro, no numbering inside the text.' +
    (hasChars ? ' CHARACTERS: begin every shot prompt with a tag like [Name1, Name2] listing EXACTLY which of the given characters appear in that shot, ' +
      'spelled exactly as given ([-] if none), then refer to them by that name in the text. Never put a character in a shot unless the story needs them there, and never invent new named characters.' : '');
}

async function genScenes({ ask, idea, n, ratio, chars, style, voice, imagePath, extra, film, retries = 3, uiLang }) {
  let text = `Idea: ${idea || '(none, invent a fitting story from the image)'}\nAspect ratio: ${ratio}\nShots: ${n}`;
  if (chars) text += `\nCharacters (keep consistent): ${chars}`;
  if (style) text += `\nVisual style: ${style}`;
  if (extra) text += '\n\n' + extra;
  const images = [];
  if (imagePath && fs.existsSync(imagePath) && /\.(jpe?g|png|webp)$/i.test(path.extname(imagePath))) {
    images.push(imagePath); text += '\nThe attached image is the product/subject to feature.';
  }
  let problem = '', lastErr = null;
  for (let i = 1; i <= retries; i++) {
    const prompt = systemPrompt(n, voice, !!chars, film) + '\n\n' + text +
      (problem ? `\n\nYOUR PREVIOUS ANSWER WAS REJECTED: ${problem}. Follow the FORMAT exactly and output exactly ${n} shots.` : '');
    try {
      const out = await ask(prompt, { images });
      const arr = parseShots(out);
      if (!arr) { problem = 'it could not be parsed'; lastErr = new Error(t(uiLang, 'spark.badFormat')); continue; }
      if (arr.length < n) { problem = `it had ${arr.length} shots instead of ${n}`; lastErr = new Error(t(uiLang, 'spark.tooFewShots', { got: arr.length, want: n })); continue; }
      return arr.slice(0, n);                       // thừa thì cắt, đủ thì dùng
    } catch (e) { lastErr = e; if (e.code === 412 || e.code === 596) break; }
  }
  throw lastErr || new Error(t(uiLang, 'spark.invalidScript'));
}
