  'Write ONE line of plain English (45-70 words) that fixes this character\'s look so an AI video model can reproduce them in every shot: ' +
  'apparent age and gender, face shape, eyes, eyebrows, nose, lips, skin tone, hairstyle with exact length and color, body build, ' +
  'then the outfit piece by piece with exact colors and materials, plus accessories. Describe only what is visible; no backstory, no mood, no background, no names. ' +
  'Output ONLY that one line, no preface.';
// Viết mô tả phong cách hình ảnh từ tên ý tưởng/phong cách (và ghi chú sẵn có nếu có)
const stylePrompt = (name, hint) => 'You are a cinematographer writing a reusable VISUAL STYLE line for an AI video generator. ' +
  'Style name (may be in Vietnamese, English, Chinese, or another language): "' + String(name || '').slice(0, 200) + '".' + (hint ? ' The user already wrote these notes, keep their meaning and improve them: "' + String(hint).slice(0, 600) + '".' : '') + '\n' +
  'Write ONE line of plain English (35-60 words) covering: overall mood, setting/era, color palette, lighting, lens and camera feel, film texture/grading. ' +
  'It must work for every shot of a story, so describe the look only: no characters, no plot, no actions, no brand or real person names, no text overlays. ' +
  'Output ONLY that one line, no preface, no quotes.';
module.exports = { genScenes, parseShots, describePrompt, stylePrompt };
