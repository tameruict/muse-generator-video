const SUPPORTED = ['vi', 'en', 'zh'];
const LOCALES = { vi: 'vi-VN', en: 'en-US', zh: 'zh-CN' };
let currentLang = 'vi';

function normalizeLang(lang) {
  return SUPPORTED.includes(lang) ? lang : 'vi';
}
function setCurrentLang(lang) {
  currentLang = normalizeLang(lang);
  return currentLang;
}
function getCurrentLang() {
  return currentLang;
}
function getLang(store) {
  const l = store && store.data && store.data.settings && store.data.settings.uiLang;
  return l ? normalizeLang(l) : currentLang;
}
function locale(lang) {
  return LOCALES[normalizeLang(lang || currentLang)] || 'vi-VN';
}

